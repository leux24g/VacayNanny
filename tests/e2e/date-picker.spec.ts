test('mobile touch calendar fits the viewport, dismisses outside and preserves dates in search', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 320, height: 740 }, isMobile: true, hasTouch: true, timezoneId: 'America/Los_Angeles' })
  const page = await context.newPage()
  try {
    await page.goto('http://localhost:3101/nannies')
    const input = page.getByLabel('Check-in', { exact: true })
    await input.tap()
    const calendar = page.getByRole('dialog', { name: 'Choose check-in date', exact: true })
    await expect(calendar).toBeVisible()
    await chooseMonth(calendar, '2027', '5')
    const box = await calendar.boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(12)
    expect(box!.x + box!.width).toBeLessThanOrEqual(308)
    expect(box!.y).toBeGreaterThanOrEqual(12)
    expect(box!.y + box!.height).toBeLessThanOrEqual(728)
    await day(calendar, '2027-06-10').tap()
    await expect(input).toHaveValue('2027-06-10')
    await page.getByLabel('Check-out', { exact: true }).fill('2027-06-10')
    await page.getByRole('button', { name: 'Open calendar for check-in date', exact: true }).tap()
    await page.getByRole('heading', { level: 1 }).tap()
    await expect(calendar).toBeHidden()
    await page.getByRole('button', { name: 'Show my matches', exact: true }).tap()
    await expect(page).toHaveURL(/checkIn=2027-06-10/)
    await expect(page).toHaveURL(/checkOut=2027-06-10/)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  } finally { await context.close() }
})

test('rescheduling uses the shared calendar and sends selected dates through the existing form', async ({ page }) => {
  await page.goto('/login')
  await enterEmailCode(page, 'family@example.test')
  await expect(page).toHaveURL('/account')
  await page.getByRole('button', { name: 'Reschedule', exact: true }).first().click()
  await page.getByRole('button', { name: 'Open calendar for new check-in date', exact: true }).click()
  const calendar = page.getByRole('dialog', { name: 'Choose new check-in date' })
  await chooseMonth(calendar, '2027', '5')
  await day(calendar, '2027-06-10').click()
  await page.getByRole('button', { name: 'Open calendar for new check-out date', exact: true }).click()
  await day(page.getByRole('dialog', { name: 'Choose new check-out date' }), '2027-06-10').click()
  let submitted: Record<string, unknown> | undefined
  await page.route('**/api/booking/*', async route => {
    submitted = route.request().postDataJSON()
    await route.fulfill({ status: 503, json: { error: 'Local test save failure' } })
  })
  await page.getByRole('button', { name: 'Save dates', exact: true }).click()
  await expect.poll(() => submitted).toMatchObject({ action: 'reschedule', checkIn: '2027-06-10', checkOut: '2027-06-10' })
})

