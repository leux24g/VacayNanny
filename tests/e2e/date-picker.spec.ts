import { test, expect, type Locator } from '@playwright/test'
import { enterEmailCode } from './auth'

async function chooseMonth(calendar: Locator, year: string, month: string) {
  await calendar.getByRole('combobox', { name: 'Choose the Year' }).selectOption(year)
  await calendar.getByRole('combobox', { name: 'Choose the Month' }).selectOption(month)
}
const day = (calendar: Locator, date: string) => calendar.locator(`[data-day="${date}"] button`)

test('homepage calendar handles date limits, same-day care, clear and readable hover states', async ({ page }, info) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Open calendar for arrival date', exact: true }).click()
  const calendar = page.getByRole('dialog', { name: 'Choose arrival date', exact: true })
  await expect(calendar).toBeVisible()
  await expect(calendar.locator('[data-disabled] button').first()).toBeDisabled()
  await chooseMonth(calendar, '2027', '5')
  await day(calendar, '2027-06-10').hover()
  await expect(day(calendar, '2027-06-10')).toHaveCSS('background-color', 'rgb(229, 236, 226)')
  await expect(day(calendar, '2027-06-10')).toHaveCSS('color', 'rgb(23, 50, 77)')
  await calendar.screenshot({ path: info.outputPath('calendar-desktop.png') })
  await day(calendar, '2027-06-10').click()
  await expect(calendar).toBeHidden()
  await expect(page.getByLabel('Arrival', { exact: true })).toHaveValue('2027-06-10')
  await page.getByRole('button', { name: 'Open calendar for departure date', exact: true }).click()
  const departure = page.getByRole('dialog', { name: 'Choose departure date' })
  await expect(day(departure, '2027-06-09')).toBeDisabled()
  await day(departure, '2027-06-10').click()
  await expect(page.getByLabel('Departure', { exact: true })).toHaveValue('2027-06-10')
  await page.getByRole('button', { name: 'Open calendar for arrival date', exact: true }).click()
  await day(calendar, '2027-06-12').click()
  await expect(page.getByLabel('Departure', { exact: true })).toHaveValue('')
  await page.getByRole('button', { name: 'Open calendar for arrival date', exact: true }).click()
  await calendar.getByRole('button', { name: 'Clear date' }).click()
  await expect(page.getByLabel('Arrival', { exact: true })).toHaveValue('')
})

test('keyboard navigation and Escape close the calendar without closing the booking form', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Start a booking' }).first().click()
  const booking = page.getByRole('dialog', { name: 'Request a nanny' })
  const input = booking.getByLabel('Check-in Date', { exact: true })
  await input.fill('2027-06-10')
  await input.focus()
  await page.keyboard.press('Alt+ArrowDown')
  const calendar = page.getByRole('dialog', { name: 'Choose check-in date', exact: true })
  await expect(day(calendar, '2027-06-10')).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(day(calendar, '2027-06-11')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(input).toHaveValue('2027-06-11')
  const trigger = booking.getByRole('button', { name: 'Open calendar for check-in date', exact: true })
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.keyboard.press('Escape')
  await expect(calendar).toBeHidden()
  await expect(booking).toBeVisible()
  await expect(trigger).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(booking).toHaveCount(0)
})

