import { test, expect } from '@playwright/test'

test('Escape dismisses an expanded booking dropdown before closing the booking form', async ({page}) => {
  await page.goto('/')
  await page.getByRole('button', {name:'Start a booking',exact:true}).first().click()
  const booking = page.getByRole('dialog', {name:'Request a nanny',exact:true})
  await booking.getByLabel('Full Name').fill('Preserved edit')
  const destination = booking.getByRole('combobox', {name:'Destination',exact:true})
  await destination.click()
  expect(await destination.evaluate(el=>el.matches(':open'))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(booking).toBeVisible()
  expect(await destination.evaluate(el=>el.matches(':open'))).toBe(false)
  await expect(booking.getByLabel('Full Name')).toHaveValue('Preserved edit')
  await page.keyboard.press('Escape')
  await expect(booking).toHaveCount(0)
})

test('month and year panels use padded choices, keyboard navigation and date boundaries', async ({ page }, info) => {
  await page.setViewportSize({width:320,height:740})
  await page.goto('/become-a-nanny')
  await page.getByRole('button', {name:'Open calendar for date of birth',exact:true}).click()
  const calendar = page.getByRole('dialog', {name:'Choose date of birth',exact:true})
  await expect(calendar.locator('select')).toHaveCount(0)
  await calendar.getByRole('button', {name:/^Choose year,/}).click()
  const years = calendar.getByRole('group', {name:'Choose a year',exact:true})
  const currentYear = years.getByRole('button', {name:'2005',exact:true})
  await expect(currentYear).toBeFocused()
  await expect(currentYear).toHaveCSS('padding-top','12px')
  await expect(currentYear).toHaveCSS('background-color','rgb(23, 50, 77)')
  await expect(calendar.getByRole('button', {name:'Next 12 years',exact:true})).toBeDisabled()
  await calendar.screenshot({path:info.outputPath('years-mobile.png')})
  await currentYear.focus()
  await page.keyboard.press('ArrowLeft')
  await expect(years.getByRole('button', {name:'2004',exact:true})).toBeFocused()
  await page.keyboard.press('Enter')
  const months = calendar.getByRole('group', {name:'Months in 2004',exact:true})
  await expect(months).toBeVisible()
  await expect(months.getByRole('button', {name:'January',exact:true})).toHaveCSS('min-height','50px')
  await months.getByRole('button', {name:'January',exact:true}).hover()
  await expect(months.getByRole('button', {name:'January',exact:true})).toHaveCSS('background-color','rgb(229, 236, 226)')
  await calendar.screenshot({path:info.outputPath('months-mobile.png')})
  await months.getByRole('button', {name:'January',exact:true}).click()
  await expect(calendar.getByRole('grid')).toBeVisible()
  await expect(page.getByLabel(/^Date of Birth/)).toHaveValue('')
  await calendar.locator('[data-day="2004-01-15"] button').click()
  await expect(page.getByLabel(/^Date of Birth/)).toHaveValue('2004-01-15')
  await page.getByRole('button', {name:'Open calendar for date of birth',exact:true}).click()
  await calendar.getByRole('button', {name:/^Choose month,/}).click()
  await calendar.getByRole('button', {name:'September',exact:true}).click()
  for (const control of [/^Choose month,/, /^Choose year,/]) {
    expect(await calendar.getByRole('button', {name:control}).locator('span').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
  }
  await calendar.getByRole('button', {name:'Close calendar',exact:true}).click()
  await page.goto('/')
  await page.getByRole('button', {name:'Open calendar for arrival date',exact:true}).click()
  const arrival = page.getByRole('dialog', {name:'Choose arrival date',exact:true})
  await arrival.getByRole('button', {name:/^Choose month,/}).click()
  const choices = arrival.getByRole('group', {name:/Months in/})
  expect(await choices.evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length)).toBe(3)
})

test('Other destination survives homepage, search and booking, and is submitted as the entered location', async ({ page }, info) => {
  await page.goto('/')
  await page.getByRole('combobox', {name:'Destination',exact:true}).selectOption({label:'Other destination'})
  const custom = page.getByRole('textbox', {name:'Your destination',exact:true})
  await expect(custom).toBeFocused()
  await expect(custom).toHaveAttribute('required','')
  await custom.fill('  Tigoni, Kiambu  ')
  await page.getByRole('button', {name:'Find a nanny',exact:true}).click()
  await expect(page).toHaveURL(/destination=Tigoni%2C\+Kiambu/)
  await expect(page.getByRole('textbox', {name:'Your destination',exact:true})).toHaveValue('Tigoni, Kiambu')
  await page.getByRole('button', {name:'Request a match',exact:true}).click()
  const booking = page.getByRole('dialog', {name:'Request a nanny',exact:true})
  await expect(booking.getByRole('textbox', {name:'Your destination',exact:true})).toHaveValue('Tigoni, Kiambu')
  await booking.getByLabel('Full Name').fill('Test Family')
  await booking.getByLabel('Email', {exact:true}).fill('family@example.test')
  await booking.getByLabel('Phone / WhatsApp').fill('+254700000000')
  await booking.getByLabel('Check-in Date', {exact:true}).fill('2027-06-10')
  await booking.getByLabel('Check-out Date', {exact:true}).fill('2027-06-10')
  await booking.getByLabel('Number of Children').selectOption('1')
  let submitted: Record<string,unknown> | undefined
  await page.route('**/api/booking', async route => {
    submitted = route.request().postDataJSON()
    await route.fulfill({status:503,json:{error:'Local test save failure'}})
  })
  await booking.getByRole('button', {name:/^Request My Nanny/}).click()
  await expect.poll(() => submitted).toMatchObject({destination:'Tigoni, Kiambu'})
  expect(submitted?.nannyId).toBeUndefined()
  await expect(booking.getByRole('textbox', {name:'Your destination',exact:true})).toHaveValue('Tigoni, Kiambu')
  await booking.screenshot({path:info.outputPath('custom-destination.png')})
  await booking.getByRole('button', {name:'Close booking form'}).click()
  await page.getByRole('button', {name:'Reset',exact:true}).click()
  await expect(page.getByRole('combobox', {name:'Destination',exact:true})).toHaveValue('')
  await expect(page.getByRole('textbox', {name:'Your destination',exact:true})).toHaveCount(0)
})

test('blank Other is blocked, switching back to a listed destination clears it, and invalid API markers are rejected', async ({ page, request }) => {
  await page.goto('/')
  const destination = page.getByRole('combobox', {name:'Destination',exact:true})
  await destination.selectOption({label:'Other destination'})
  await page.getByRole('button', {name:'Find a nanny',exact:true}).click()
  await expect(page).toHaveURL('/')
  await page.getByRole('textbox', {name:'Your destination',exact:true}).fill('   ')
  expect(await page.getByRole('textbox', {name:'Your destination',exact:true}).evaluate((el:HTMLInputElement)=>el.checkValidity())).toBe(false)
  await destination.selectOption('Diani')
  await expect(page.getByRole('textbox', {name:'Your destination',exact:true})).toHaveCount(0)
  await page.getByRole('button', {name:'Find a nanny',exact:true}).click()
  await expect(page).toHaveURL(/destination=Diani/)
  for (const value of ['Other', '__other_destination__', ['Diani','Tigoni']]) {
    const response = await request.post('/api/booking', {data:{parentName:'Test',email:'test@example.test',destination:value,checkIn:'2027-06-10',checkOut:'2027-06-10'}})
    expect(response.status()).toBe(400)
    expect((await response.json()).error).toContain('one destination')
  }
})

